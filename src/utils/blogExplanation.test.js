import { beforeEach, afterEach, it, expect, vi } from 'vitest'
import { requestBlogExplanation } from './blogExplanation.js'
const reply = (status, data) => ({ status, ok: status === 200, headers: new Headers({ 'Retry-After': '1' }), json: async () => data })
beforeEach(() => vi.useFakeTimers())
afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals() })
it('retries a pre-generation database failure once and returns the summary', async () => {
  const fetch = vi.fn().mockResolvedValueOnce(reply(503, { code: 'DATABASE_UNAVAILABLE' })).mockResolvedValue(reply(200, { reply: 'A real summary.' }))
  vi.stubGlobal('fetch', fetch)
  const retry = vi.fn()
  const result = requestBlogExplanation({ postId: 'post', mode: 'tldr', onRetry: retry })
  await vi.advanceTimersByTimeAsync(1000)
  expect((await result).reply).toBe('A real summary.')
  expect(retry).toHaveBeenCalledOnce()
  expect(fetch).toHaveBeenCalledTimes(2)
})
it('stops after two database failures', async () => {
  const fetch = vi.fn().mockResolvedValue(reply(503, { code: 'DATABASE_UNAVAILABLE' }))
  vi.stubGlobal('fetch', fetch)
  const result = requestBlogExplanation({ postId: 'post', mode: 'junior' }).catch(e => e)
  await vi.advanceTimersByTimeAsync(1000)
  expect((await result).code).toBe('DATABASE_UNAVAILABLE')
  expect(fetch).toHaveBeenCalledTimes(2)
})
it('does not retry provider errors or spend another generation call', async () => {
  const fetch = vi.fn().mockResolvedValue(reply(500, { error: 'Provider error' }))
  vi.stubGlobal('fetch', fetch)
  await expect(requestBlogExplanation({ postId: 'post', mode: 'tldr' })).rejects.toThrow('Provider error')
  expect(fetch).toHaveBeenCalledOnce()
})
it('cancels the retry when the article is left', async () => {
  const fetch = vi.fn().mockResolvedValue(reply(503, { code: 'DATABASE_UNAVAILABLE' }))
  vi.stubGlobal('fetch', fetch)
  const controller = new AbortController()
  const result = requestBlogExplanation({ postId: 'post', mode: 'tldr', signal: controller.signal }).catch(e => e)
  await vi.advanceTimersByTimeAsync(0)
  controller.abort()
  await vi.advanceTimersByTimeAsync(1000)
  expect((await result).name).toBe('AbortError')
  expect(fetch).toHaveBeenCalledOnce()
})
it('rejects successful-looking empty replies', async () => {
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue(reply(200, { reply: '' })))
  await expect(requestBlogExplanation({ postId: 'post', mode: 'tldr' })).rejects.toThrow('Empty summary')
})
