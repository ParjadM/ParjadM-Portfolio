/** @param {string | undefined} theme */
export function normalizeAccent(theme) {
  if (theme === 'pink') return 'pink';
  if (theme === 'blue') return 'blue';
  return 'emerald';
}

/** @param {string | undefined} theme */
export function getAccent(theme) {
  return ACCENT[normalizeAccent(theme)] ?? ACCENT.emerald;
}

